export const MEMORY_SYSTEM = `你是这段互动小说的"故事守护者"。你会严格参照用户消息中的故事大纲、世界书、上一版长期记忆、最近对话、状态提取、人物档案、背包、当前场景和玩家标记，把后续故事写手最容易忘记的稳定事实整理成短而可用的记忆块。

长期一致性记忆整理规则：把上一版长期记忆、最近对话、决策模型提取到的状态变化，合并为一份更准确、更短、更便于故事模型使用的【长期一致性记忆】。

只输出记忆正文，不要输出解释、前言、JSON、代码块或 Markdown 标题。

整理原则：
1. 只保留会影响后续连续性的事实：人物外观/服装/习惯/称呼/关系变化、主角承诺或计划、未解线索、物品状态、地点状态、时间安排、重要情绪债。
2. 所有人物信息必须以主角视角表述。主角不知道的真实身份、隐藏动机、幕后秘密不能写成事实；只能写成"我怀疑/我感觉/似乎/可能"。
3. 区分临时状态与稳定设定：例如"上次见面穿 JK 服"和"常常穿 JK 服"不能混淆；只有多次证据才写"常常"。
4. 新信息与旧记忆冲突时，用新信息更新旧记忆；已解决、失效或不再重要的条目应删除。
5. 玩家通过【玩家标记的关键记忆】明确标记的内容必须保留——除非它本身已被推翻或自然解决——并优先以"主角承诺/计划/未解线索"形式落入条目，永不静默丢弃。
6. ★ **世界书一致性**：若提供【世界书 · 硬设定】，记忆里涉及相关机制（如能力规则、世界基调）的描述**必须与之兼容**；不要把"主动施用"误录为"被动反应"，不要把已明确的世界规则写成"似乎/可能"。
7. ★ **大纲对齐**：若提供【故事大纲】，记忆应当把已发生的剧情**对应到大纲幕次**（例：可在条目末尾轻标"（呼应第一幕'觉醒'）"），便于下游故事模型对齐主线；但不要剧透未发生的幕次。
8. 尽量短句、可引用、可执行；不要复述整段剧情，不要写文学化正文。
9. 输出总长度必须不超过用户给定的上限。`;

export function buildMemoryUser(p: {
  previousMemory?: string;
  recentText: string;
  decisionText: string;
  npcText: string;
  backpackText: string;
  currentSceneText: string;
  anchorsText?: string;
  outlineText?: string;
  worldBookText?: string;
  maxChars: number;
}): string {
  const lines: string[] = [
    '建议格式（可省略空类目）：',
    '- 人物：小晴｜粉色美甲；上次见面穿 JK 服；我感觉她可能对主角有好感。',
    '- 承诺/计划：主角答应明晚去旧图书馆找她。',
    '- 线索/物品：银钥匙来自地下室，尚未试过三楼铁门。',
    '- 场景/时间：当前是雨夜，主角在校门口附近。',
    '',
  ];
  if (p.outlineText?.trim()) {
    lines.push('【故事大纲】（仅作对齐参考，不要剧透未来幕次）', p.outlineText.trim(), '');
  }
  if (p.worldBookText?.trim()) {
    lines.push('【世界书 · 硬设定】（记忆描述涉及这些机制时必须兼容）', p.worldBookText.trim(), '');
  }
  lines.push(
    '【上一版长期记忆】',
    p.previousMemory?.trim() || '（无）',
    '',
    '【最近对话】',
    p.recentText.trim() || '（无）',
    '',
    '【本轮决策/状态提取】',
    p.decisionText.trim() || '（无）',
    '',
    '【当前人物档案】',
    p.npcText.trim() || '（无）',
    '',
    '【当前背包】',
    p.backpackText.trim() || '（空）',
    '',
    '【当前场景】',
    p.currentSceneText.trim() || '（不明）',
    '',
  );
  if (p.anchorsText?.trim()) {
    lines.push(
      '【玩家标记的关键记忆】（必须保留并以承诺/计划/未解线索/伏笔等形式落地）',
      p.anchorsText.trim(),
      '',
    );
  }
  lines.push(
    '【当前上下文 / 整理任务】',
    `请把以上信息合并为最新长期一致性记忆，最长 ${p.maxChars} 个汉字左右。`,
    '',
    '请输出更新后的长期一致性记忆正文。',
  );
  return lines.join('\n');
}

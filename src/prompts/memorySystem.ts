export const MEMORY_SYSTEM = `你是文字 RPG 的长期一致性记忆整理助手。你的任务是把上一版长期记忆、最近对话、决策模型提取到的状态变化，合并为一份更准确、更短、更便于故事模型使用的【长期一致性记忆】。

只输出记忆正文，不要输出解释、前言、JSON、代码块或 Markdown 标题。

整理原则：
1. 只保留会影响后续连续性的事实：人物外观/服装/习惯/称呼/关系变化、主角承诺或计划、未解线索、物品状态、地点状态、时间安排、重要情绪债。
2. 所有人物信息必须以主角视角表述。主角不知道的真实身份、隐藏动机、幕后秘密不能写成事实；只能写成"我怀疑/我感觉/似乎/可能"。
3. 区分临时状态与稳定设定：例如"上次见面穿 JK 服"和"常常穿 JK 服"不能混淆；只有多次证据才写"常常"。
4. 新信息与旧记忆冲突时，用新信息更新旧记忆；已解决、失效或不再重要的条目应删除。
5. 尽量短句、可引用、可执行；不要复述整段剧情，不要写文学化正文。
6. 输出总长度必须不超过用户给定的上限。`;

export function buildMemoryUser(p: {
  previousMemory?: string;
  recentText: string;
  decisionText: string;
  npcText: string;
  backpackText: string;
  currentSceneText: string;
  maxChars: number;
}): string {
  return [
    `请把以下信息合并为最新长期一致性记忆，最长 ${p.maxChars} 个汉字左右。`,
    '',
    '建议格式（可省略空类目）：',
    '- 人物：小晴｜粉色美甲；上次见面穿 JK 服；我感觉她可能对主角有好感。',
    '- 承诺/计划：主角答应明晚去旧图书馆找她。',
    '- 线索/物品：银钥匙来自地下室，尚未试过三楼铁门。',
    '- 场景/时间：当前是雨夜，主角在校门口附近。',
    '',
    '【上一版长期记忆】',
    p.previousMemory?.trim() || '（无）',
    '',
    '【最近对话】',
    p.recentText.trim() || '（无）',
    '',
    '【本轮决策/状态提取】',
    p.decisionText.trim() || '（无）',
    '',
    '【当前人物档案】',
    p.npcText.trim() || '（无）',
    '',
    '【当前背包】',
    p.backpackText.trim() || '（空）',
    '',
    '【当前场景】',
    p.currentSceneText.trim() || '（不明）',
    '',
    '请输出更新后的长期一致性记忆正文。',
  ].join('\n');
}
